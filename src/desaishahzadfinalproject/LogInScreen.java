    private void btnLogInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogInActionPerformed
        //when the log in button is clicked

        String username = txtFieldUsername.getText();//get the username given
        if (username.length() == 0 || passwordField.getPassword().length == 0) { //check if a username or password was not given
            //display the appropriate message
            JOptionPane.showMessageDialog(null, "Username or password not entered, please try again.");
        } else { //everything necessary was given
            try {//try this block of code
                FileInputStream in; //declare a FileInputStream 
                if (System.getProperty("user.dir").substring(System.getProperty("user.dir").length() - 4, System.getProperty("user.dir").length()).equals("dist")) {//check if the file path of the user is in the dist folder
                    in = new FileInputStream(System.getProperty("user.dir") + "/saves/users.txt"); //instantiate a new FileInputStream with the right file path
                } else { //must not be in the dist folder
                    in = new FileInputStream(System.getProperty("user.dir") + "/dist/saves/users.txt");//instantiate a new FileInputStream with the right file path
                }

                try { //try this block of code
                    ObjectInputStream s = new ObjectInputStream(in); //instantiate a new ObjectInputStream with the given FileInputStream
                    ArrayList<User> users = (ArrayList<User>) s.readObject(); //get the array lsit of users that are signed up by reading an object from the file

                    boolean successLogIn = false; //declare and assign a boolean that tracks if there was a successful log in or not
                    for (int i = 0; i < users.size(); i++) { //loop through the current users signed up

                        User u = users.get(i); //get the  user at the current index
                        if (u.getPassword().equals(String.copyValueOf(passwordField.getPassword())) && u.getUsername().equals(username)) { //check if the username and password entered match the username and password of the current user
                            //clear both the text and password field
                            txtFieldUsername.setText("");
                            passwordField.setText("");

                            JOptionPane.showMessageDialog(null, "Log-in Successful");//display that the log in was a success 
                            mainUser = u; //set the mainUser (one that is signed in) to the current user
                            successLogIn = true; //set the succesful log in boolean to true
                        }
                    }

                    if (!successLogIn) { //check if there wasn't a successful log in
                        //display the appropriate message
                        JOptionPane.showMessageDialog(null, "Log-in Failed");
                    } else {//was a successful log in
                        this.setVisible(false); //set this window so it is not visible
                        mainMenuScreen = new MainMenuScreen(mainUser, this, new StockScreen(mainUser), new PortfolioScreen(mainUser)); //instantiate a new MainMenuScreen
                        mainMenuScreen.setVisible(true);//display the main menu screen
                    }

                } catch (ClassNotFoundException e) { //catch a ClassNotFoundException
                    //display the appropriate error message
                    JOptionPane.showMessageDialog(null, "Error!");
                }

            } catch (IOException e) { //catch a IOException 
                //display the appropriate error message
                JOptionPane.showMessageDialog(null, "Error! No accounts have been made yet, go sign up");
            }
        }

    }//GEN-LAST:event_btnLogInActionPerformed

