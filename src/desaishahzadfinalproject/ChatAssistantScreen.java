    private void btnSendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendActionPerformed
        //if send button is pressed
        String prompt = txtPrompt.getText(); //get user's prompt
        String model = "gpt-4o-mini"; //model of chatGPT used - 4o mini

        try {
            //create the HTTP POST request
            //create the chatgpt URL where API requests are to be sent
            URL obj = new URL(API_URL);
            //open connection to chatGPT URL
            HttpURLConnection con = (HttpURLConnection) obj.openConnection();
            //set request methods and properties with API key
            con.setRequestMethod("POST");
            //authorization HTTP header that includes the API key
            con.setRequestProperty("Authorization", "Bearer " + API_KEY);
            con.setRequestProperty("Content-Type", "application/json");

            //add extra info to the prompt so the information given doesn't have random characters because the data is being formatted by the server
            prompt += ". The message is everything before this. Only respond to the message and nothing after but DO NOT IGNORE THE REQUEST AFTER THIS. This is the request that is not to be acknowledged in your response back: Please DO NOT format the response in any way including bullet points, headers, bolded text, new line breaks etc. Just return the response as a single or multiple paragraphs.";
            //build the request message that includes the model to be used and the user's prompt
            String body = "{\"model\": \"" + model + "\", \"messages\": [{\"role\": \"user\", \"content\": \"" + prompt + "\"}]}";
            con.setDoOutput(true);
            //OutputStreamWriter for sending our message to the ChatGPT API
            OutputStreamWriter writer = new OutputStreamWriter(con.getOutputStream());
            //send message
            writer.write(body);
            //flush and close the writer now that the message has been sent
            writer.flush();
            writer.close();

            //Get the message from the API using a BufferedReader
            BufferedReader in = new BufferedReader(new InputStreamReader(con.getInputStream()));
            StringBuffer response = new StringBuffer();
            String inputLine;
            while ((inputLine = in.readLine()) != null) { //while the input from ChatGPT is not null
                //add the current input to the input string
                response.append(inputLine);
            }
            //close the reader connection once done
            in.close();

            //user method to extract and format json reponse provided by the api
            String output = extractContentFromResponse(response.toString());
            output = output.replace("\n", ""); //remove any formatting provided by api
            txtResponse.setText(output); //display response to user

        } catch (IOException e) { //catch any IO exception
            //output a response telling the user to check their internet connection or openAI status
            txtResponse.setText("An error has occured. Please check your internet status or go to https://status.openai.com/ in your browser to check the status of the chat assistant powered by OpenAI.");
        }
    }//GEN-LAST:event_btnSendActionPerformed
    /**
     * Extracts the actual chat model response from a ChatGPT API response that
     * contains various fields
     *
     * @param response - the response to get message from
     * @return the extracted message
     */
    private String extractContentFromResponse(String response) {
        //marker for where the content starts, finding where the response contains content then adding 11 as there are exactly 11 characters until the actual message
        int startMarker = response.indexOf("content") + 11;
        //marker for where the content ends, which is a \ right after the message
        int endMarker = response.indexOf("\"", startMarker);
        //returns the substring containing only the response from the start marker to the end marker that were found.
        String content = response.substring(startMarker, endMarker);
        return content;
    }


