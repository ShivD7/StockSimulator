    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed
        User client = new User(); //instantiate a new User
        users = load(); //load all of the current users signed up
        try {//try this block of code
            FileOutputStream out; //declare a FileOutputStream
            if (System.getProperty("user.dir").substring(System.getProperty("user.dir").length() - 4, System.getProperty("user.dir").length()).equals("dist")) { //check if the user is in the dist folder (JAR is running)
                out = new FileOutputStream(System.getProperty("user.dir") + "/saves/users.txt"); //instantitate a new FileOutputStream with the correct file path
            } else {//must not be in the dist folder
                out = new FileOutputStream(System.getProperty("user.dir") + "/dist/saves/users.txt");//instantitate a new FileOutputStream with the correct file path
            }

            ObjectOutput s = new ObjectOutputStream(out);//instantitate a new ObjectOutputStream to write out objects to a file

            if (txtFieldUsername.getText().length() == 0 || passwordField.getPassword().length == 0) { //check if a username or password was not entered
                //display the appropriate message
                JOptionPane.showMessageDialog(null, "You have not entered a username or password! Please try again.");
            } else if (txtFieldUsername.getText().length() > 10) { //check if the username provided is more than 10 characters in length
                //display the appropriate message
                JOptionPane.showMessageDialog(null, "Username too long, must be less than or equal to 10 characters in length.\nPlease try again!");
            } else { //all of the information provided must be fine
                boolean isSameUsername = false; //declare a boolean to track if there is 2 users with the same username
                for (int i = 0; i < users.size(); i++) { //loop through all of the users in the list
                    User u = users.get(i); //get the user at the current index
                    if (u.getUsername().equals(txtFieldUsername.getText())) { //compare the usernames, check if they are equal
                        isSameUsername = true; //set the variable to true
                    }
                }
                if (isSameUsername) { //check if there are 2 users with the same username
                    //this can't happen, display the error message
                    JOptionPane.showMessageDialog(null, "Sorry, username is taken. Please try again!");
                } else {//must be fine
                    client = new User(txtFieldUsername.getText(), String.copyValueOf(passwordField.getPassword())); //instantiate a new user with the given username and password
                    //clear the text fields
                    txtFieldUsername.setText("");
                    passwordField.setText("");
                    users.add(client); //add the new user to the list of users
                    JOptionPane.showMessageDialog(null, "You have successfully created an account!"); //display that an account has been made
                }
            }
            s.writeObject(users); //write the new list of users to the file
            s.close();//close the ObjectOutputStream
        } catch (IOException e) { //catch an IOException
            //display the appropriate error message
            JOptionPane.showMessageDialog(null, "Error!" + e);
        } catch (Exception e) {//catch any other error
            //display the appropriate error message
            JOptionPane.showMessageDialog(null, "Error!" + e);
        }


    }//GEN-LAST:event_btnSignUpActionPerformed

